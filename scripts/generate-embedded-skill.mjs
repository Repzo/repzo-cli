#!/usr/bin/env node

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const skillRoot = join(packageRoot, "skills", "repzo-workstation");
const outputPath = join(packageRoot, "lib", "embedded-skill.generated.mjs");
const checkOnly = process.argv.includes("--check");

async function filesUnder(directory) {
	const files = [];
	async function walk(current) {
		for (const entry of await readdir(current, { withFileTypes: true })) {
			const path = join(current, entry.name);
			if (entry.isDirectory()) await walk(path);
			else if (entry.isFile()) files.push(path);
		}
	}
	await walk(directory);
	return files.sort();
}

const entries = await Promise.all(
	(await filesUnder(skillRoot)).map(async (path) => [
		relative(skillRoot, path).replaceAll("\\", "/"),
		await readFile(path, "utf8"),
	]),
);
const generated = `// Generated by scripts/generate-embedded-skill.mjs. Do not edit.\nexport const EMBEDDED_SKILL_FILES = Object.freeze(${JSON.stringify(Object.fromEntries(entries), null, "\t")});\n`;

if (checkOnly) {
	const existing = await readFile(outputPath, "utf8").catch(() => "");
	if (existing !== generated) {
		console.error("Embedded Repzo skill is stale. Run: npm run skill:embed");
		process.exit(1);
	}
	console.log(`Embedded Repzo skill matches ${entries.length} source files.`);
} else {
	await writeFile(outputPath, generated);
	console.log(`Embedded ${entries.length} Repzo skill files.`);
}
