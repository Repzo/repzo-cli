#!/usr/bin/env node

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const skillNames = ["repzo-workstation", "repzo-ai-agents"];
const outputPath = join(packageRoot, "lib", "embedded-skill.generated.mjs");
const checkOnly = process.argv.includes("--check");

async function filesUnder(directory) {
	const files = [];
	async function walk(current) {
		for (const entry of await readdir(current, { withFileTypes: true })) {
			const path = join(current, entry.name);
			if (entry.isDirectory()) await walk(path);
			else if (entry.isFile()) files.push(path);
		}
	}
	await walk(directory);
	return files.sort();
}

const embeddedSkills = Object.fromEntries(await Promise.all(skillNames.map(async (skillName) => {
	const skillRoot = join(packageRoot, "skills", skillName);
	const entries = await Promise.all((await filesUnder(skillRoot)).map(async (path) => [
		relative(skillRoot, path).replaceAll("\\", "/"),
		await readFile(path, "utf8"),
	]));
	return [skillName, Object.fromEntries(entries)];
})));
const fileCount = Object.values(embeddedSkills).reduce((total, files) => total + Object.keys(files).length, 0);
const generated = `// Generated by scripts/generate-embedded-skill.mjs. Do not edit.\nexport const EMBEDDED_SKILLS = Object.freeze(${JSON.stringify(embeddedSkills, null, "\t")});\n`;

if (checkOnly) {
	const existing = await readFile(outputPath, "utf8").catch(() => "");
	if (existing !== generated) {
		console.error("Embedded Repzo skill is stale. Run: npm run skill:embed");
		process.exit(1);
	}
	console.log(`Embedded Repzo skills match ${fileCount} source files.`);
} else {
	await writeFile(outputPath, generated);
	console.log(`Embedded ${fileCount} Repzo skill files across ${skillNames.length} skills.`);
}
